/**
 * Bakes the cash.builds workspace page into the worker bundle.
 *
 * The page used to live as a claude.ai artifact, where the sandbox blocked both
 * the claudework:// launcher and any call to this worker — so "Refresh" could
 * never actually refresh. Served from here it is same-origin with the stats it
 * displays, and the session cookie already gates it.
 *
 * Run `npm run build:workspace` after editing the source page.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = process.env.WORKSPACE_HTML_SRC
  ?? join(root, "..", "cash-builds", "dashboard.html");
const OUT = join(root, "src", "workspace-html.ts");

const html = readFileSync(SOURCE, "utf8");

writeFileSync(
  OUT,
  `// GENERATED by scripts/build-workspace.mjs — do not edit.\n` +
    `// Source: cash-builds/dashboard.html (${html.length} bytes)\n` +
    `export const WORKSPACE_HTML = ${JSON.stringify(html)};\n`,
);

console.log(`workspace: ${html.length} bytes -> src/workspace-html.ts`);
